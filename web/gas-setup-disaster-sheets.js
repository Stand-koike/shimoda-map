/**
 * メニュー実行用。既存の getTargetSpreadsheet_ / getWebhookSheetId_ があれば利用。
 */
function setupDisasterSheets() {
  var ss = disasterGetSpreadsheet_();
  ensureEvacuationPlacesSheet_(ss);
  ensureEvacuationSheltersSheet_(ss);
  console.log('setupDisasterSheets: OK');
}

function disasterGetSpreadsheet_() {
  if (typeof getTargetSpreadsheet_ === 'function') return getTargetSpreadsheet_();
  var id = '';
  if (typeof getWebhookSheetId_ === 'function') id = getWebhookSheetId_() || '';
  if (!id) {
    try {
      var props = PropertiesService.getScriptProperties();
      id = props.getProperty('SHEET_ID') || props.getProperty('YOUR_GOOGLE_SHEET_ID') || '';
    } catch (e) { /* ignore */ }
  }
  if (id) return SpreadsheetApp.openById(String(id).trim());
  var active = SpreadsheetApp.getActiveSpreadsheet();
  if (active) return active;
  throw new Error('対象スプレッドシートを開くか、SHEET_ID を設定してください。');
}

function disasterInsertSheetAtEnd_(ss, name) {
  var existing = ss.getSheetByName(name);
  if (existing) return existing;
  if (typeof setupInsertSheetAtEnd_ === 'function') return setupInsertSheetAtEnd_(ss, name);
  var n = ss.getSheets().length;
  return ss.insertSheet(name, n + 1);
}

function disasterStyleHeader_(sheet, numCols, hex) {
  sheet.getRange(1, 1, 1, numCols)
    .setBackground(hex)
    .setFontColor('#FFFFFF')
    .setFontWeight('bold');
  sheet.setFrozenRows(1);
}

function ensureEvacuationPlacesSheet_(ss) {
  var sheet = disasterInsertSheetAtEnd_(ss, DISASTER_SHEET_NAMES.PLACES);
  var header = sheet.getRange(1, 1, 1, EVAC_PLACES_HEADERS.length).getValues()[0];
  var headerOk = String(header[0]) === 'id' && String(header[2]) === 'name';
  if (!headerOk) {
    sheet.clear();
    sheet.getRange(1, 1, 1, EVAC_PLACES_HEADERS.length).setValues([EVAC_PLACES_HEADERS]);
  }
  disasterStyleHeader_(sheet, EVAC_PLACES_HEADERS.length, '#C62828');
  if (sheet.getLastRow() <= 1) {
    sheet.getRange(2, 1, EVAC_PLACES_ROWS.length, EVAC_PLACES_HEADERS.length)
      .setValues(EVAC_PLACES_ROWS);
  }
  return sheet;
}

