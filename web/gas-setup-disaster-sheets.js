function disasterGetSpreadsheet_() {
  if (typeof getTargetSpreadsheet_ === 'function') return getTargetSpreadsheet_();
  var id = '';
  if (typeof getWebhookSheetId_ === 'function') id = getWebhookSheetId_() || '';
  if (!id) {
    try {
      var props = PropertiesService.getScriptProperties();
      id = props.getProperty('SHEET_ID') || props.getProperty('YOUR_GOOGLE_SHEET_ID') || '';
    } catch (e) { /* ignore */ }
  }
  if (id) return SpreadsheetApp.openById(String(id).trim());
  var active = SpreadsheetApp.getActiveSpreadsheet();
  if (active) return active;
  throw new Error('対象スプレッドシートを開くか、SHEET_ID を設定してください。');
}

function disasterInsertSheetAtEnd_(ss, name) {
  var existing = ss.getSheetByName(name);
  if (existing) return existing;
  if (typeof setupInsertSheetAtEnd_ === 'function') return setupInsertSheetAtEnd_(ss, name);
  var n = ss.getSheets().length;
  return ss.insertSheet(name, n + 1);
}

function disasterStyleHeader_(sheet, numCols, hex) {
  sheet.getRange(1, 1, 1, numCols)
    .setBackground(hex)
    .setFontColor('#FFFFFF')
    .setFontWeight('bold');
  sheet.setFrozenRows(1);
}

